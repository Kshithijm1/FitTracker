import UIKit

/// Thin wrapper so feature code never touches UIKit feedback generators
/// directly. `.light` on every log action, `.success` on PR/goal close.
enum Haptics {
    static func light() {
        UIImpactFeedbackGenerator(style: .light).impactOccurred()
    }

    static func success() {
        UINotificationFeedbackGenerator().notificationOccurred(.success)
    }

    static func warning() {
        UINotificationFeedbackGenerator().notificationOccurred(.warning)
    }
}
